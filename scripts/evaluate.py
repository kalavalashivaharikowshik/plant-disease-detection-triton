"""Evaluate the served model with the exact production pipeline.

Expects a folder laid out like PlantVillage (one sub-folder per class id):

    data/Tomato___Late_blight/*.jpg
    data/Apple___healthy/*.jpg
    ...

Example (PlantVillage from GitHub, 10 random images per class):

    git clone --depth 1 --filter=blob:none --sparse https://github.com/spMohanty/PlantVillage-Dataset pv
    python scripts/evaluate.py --data pv/raw/color --per-class 10 --out docs/evaluation.md

Reports top-1 / top-3 accuracy, per-class accuracy, the most common confusions and,
importantly, how accurate the app is when it marks a result "reliable" versus when it
shows a warning.
"""

from __future__ import annotations

import argparse
import asyncio
import random
import sys
from collections import Counter, defaultdict
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1] / "backend"
sys.path.insert(0, str(BACKEND))

from app.config import Settings  # noqa: E402
from app.main import build_state  # noqa: E402


async def evaluate(data_dir: Path, per_class: int, seed: int) -> dict:
    settings = Settings(inference_backend="onnx", explanation_provider="static", redis_url="")
    state = build_state(settings)
    rng = random.Random(seed)
    rows = []
    for class_dir in sorted(p for p in data_dir.iterdir() if p.is_dir()):
        if class_dir.name not in state.kb.diseases:
            print(f"skip unknown class folder {class_dir.name}", file=sys.stderr)
            continue
        files = sorted(class_dir.glob("*.[jJpP][pPnN]*[gG]"))
        for path in rng.sample(files, min(per_class, len(files))):
            result = await state.predictor.analyze(path.read_bytes())
            rows.append({
                "true": class_dir.name,
                "pred": result["prediction"]["class_id"],
                "top3": [s["class_id"] for s in result["top_k"]],
                "confidence": result["prediction"]["confidence"],
                "reliable": result["reliable"],
            })
    return {"rows": rows, "kb": state.kb}


def report(rows: list[dict], kb, data_dir: Path, per_class: int) -> str:
    n = len(rows)
    top1 = sum(r["true"] == r["pred"] for r in rows)
    top3 = sum(r["true"] in r["top3"] for r in rows)
    reliable = [r for r in rows if r["reliable"]]
    flagged = [r for r in rows if not r["reliable"]]

    def acc(items):
        return sum(r["true"] == r["pred"] for r in items) / len(items) if items else float("nan")

    per = defaultdict(lambda: [0, 0])
    for r in rows:
        per[r["true"]][1] += 1
        per[r["true"]][0] += r["true"] == r["pred"]
    confusions = Counter((r["true"], r["pred"]) for r in rows if r["true"] != r["pred"])
    name = lambda cid: kb.get(cid).display_name  # noqa: E731

    lines = [
        "# Model evaluation",
        "",
        f"Generated by `scripts/evaluate.py` on `{data_dir.name}` with {per_class} random images per class "
        f"({n} images, {len(per)} classes), using the production pipeline (EXIF handling, preprocessing, "
        "stability check and quality check).",
        "",
        "## Headline numbers",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Top-1 accuracy | **{top1 / n:.1%}** ({top1}/{n}) |",
        f"| Top-3 accuracy | {top3 / n:.1%} ({top3}/{n}) |",
        f"| Results marked reliable | {len(reliable) / n:.1%} of images |",
        f"| Accuracy when marked reliable | **{acc(reliable):.1%}** ({len(reliable)} images) |",
        f"| Accuracy when a warning was shown | {acc(flagged):.1%} ({len(flagged)} images) |",
        "",
        "The reliability flag is the point of the app: when LeafScan says a result is reliable it is right "
        "far more often, and most mistakes arrive with a warning that tells the user to double-check.",
        "",
        "## Most common confusions",
        "",
        "| True class | Predicted as | Count |",
        "|---|---|---|",
    ]
    lines += [f"| {name(t)} | {name(p)} | {c} |" for (t, p), c in confusions.most_common(8)]
    lines += ["", "## Per-class accuracy", "", "| Class | Correct |", "|---|---|"]
    for cid, (ok, total) in sorted(per.items(), key=lambda kv: (kv[1][0] / kv[1][1], kv[0])):
        lines.append(f"| {name(cid)} | {ok}/{total} |")
    lines += [
        "",
        "## Caveats",
        "",
        "- PlantVillage photos show one leaf on a plain background in controlled light. The model was "
        "trained on an augmented copy of the same dataset, so some test images may overlap with "
        "training data and these numbers are optimistic.",
        "- Expect lower accuracy on field photos (several leaves, soil, shadows). Fine-tuning on a "
        "field dataset such as PlantDoc is the main next step.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--per-class", type=int, default=10)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()

    result = asyncio.run(evaluate(args.data, args.per_class, args.seed))
    text = report(result["rows"], result["kb"], args.data, args.per_class)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")
    print(text.split("## Most common")[0])


if __name__ == "__main__":
    main()
